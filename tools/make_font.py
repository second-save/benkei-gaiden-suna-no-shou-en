def _encode_glyph(rows: list[str]) -> bytes:
    buf = bytearray(16)
    for idx, line in enumerate(rows):
        if len(line) > 7:
            raise ValueError(f"Glyph row {line!r} exceeds 7px art limit")
        val = 0
        for col, ch in enumerate(line):
            if ch == "#":
                val |= 0x80 >> col
        buf[4 + idx] = val
    return bytes(buf)


def build_font_binaries() -> tuple[bytes, bytes]:
    """Build 2,048-byte 1bpp font and 128-byte advance-width table for $00-$7F."""
    font = bytearray(128 * 16)
    widths = bytearray([8] * 128)

    # $00-$0F: fixed-width digits/hex matching ASCII 0-9, A-F
    for d in range(10):
        raw = _encode_glyph(GLYPHS[str(d)])
        font[d * 16 : (d + 1) * 16] = raw
    for h in range(6):
        raw = _encode_glyph(GLYPHS[chr(ord("A") + h)])
        code = 0x0A + h
        font[code * 16 : (code + 1) * 16] = raw

    # $10: blank 8px pad; $11-$1F: fixed punctuation matching stock $00:EA40 static tiles
    punct_map = {
        0x11: '"',
        0x12: "!",
        0x13: "?",
        0x14: ":",
        0x15: "-",
        0x16: "\\",
        0x17: "/",
        0x18: ".",
        0x19: ",",
        0x1A: "[",
        0x1B: "]",
        0x1C: ".",
        0x1D: "'",
        0x1E: "(",
        0x1F: ")",
    }
    for code, ch in punct_map.items():
        font[code * 16 : (code + 1) * 16] = _encode_glyph(GLYPHS[ch])

    # $20-$7E: proportional ASCII
    widths[0x20] = 4
    for code in range(0x21, 0x7F):
        ch = chr(code)
        raw = _encode_glyph(GLYPHS[ch])
        font[code * 16 : (code + 1) * 16] = raw
        max_col = -1
        for b in raw:
            for c in range(8):
                if b & (0x80 >> c):
                    max_col = max(max_col, c)
        if max_col < 0:
            raise ValueError(f"Empty glyph for ASCII {ch!r}")
        if max_col > 6:
            raise ValueError(f"Glyph {ch!r} touches col {max_col} > 6")
        adv = max(3, min(8, max_col + 2))
        widths[code] = adv

    return bytes(font), bytes(widths)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="Verify existing binaries without rewriting")
    args = ap.parse_args(argv)

    font, widths = build_font_binaries()
    if args.check:
        if OUT_FONT.read_bytes() != font or OUT_WIDTHS.read_bytes() != widths:
            print("font binaries out of sync with tools/make_font.py", file=sys.stderr)
            return 1
        print("font check ok: 2048 B font, 128 B widths")
        return 0

    ASM_DIR.mkdir(parents=True, exist_ok=True)
    OUT_FONT.write_bytes(font)
    OUT_WIDTHS.write_bytes(widths)
    print(f"wrote {OUT_FONT.relative_to(ROOT)} ({len(font)} B) and {OUT_WIDTHS.relative_to(ROOT)} ({len(widths)} B)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
